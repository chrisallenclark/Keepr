#!/usr/bin/env python3
"""Turns design/sf-symbols.tsv into Android vector drawables and a lookup table.

Material Symbols (Apache 2.0) come from npm, one package per weight:

    npm pack @material-symbols/svg-400 @material-symbols/svg-600
    tar xzf material-symbols-svg-400-*.tgz --one-top-level=svg-400
    tar xzf material-symbols-svg-600-*.tgz --one-top-level=svg-600

Usage: generate_icons.py DIR_CONTAINING_svg-400_AND_svg-600

Writes app/src/main/res/drawable/sf_*.xml and
app/src/main/java/com/chrisallenclark/keepr/ui/icons/SfSymbolTable.kt.
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
TABLE = ROOT / "design/sf-symbols.tsv"
RES = ROOT / "app/src/main/res/drawable"
KOTLIN = ROOT / "app/src/main/java/com/chrisallenclark/keepr/ui/icons/SfSymbolTable.kt"


def resource_name(sf_name: str) -> str:
    return "sf_" + re.sub(r"[^a-z0-9]", "_", sf_name)


def vector(svg: str) -> str:
    view_box = re.search(r'viewBox="([^"]+)"', svg).group(1).split()
    min_x, min_y, width, height = (float(v) for v in view_box)
    paths = re.findall(r'<path[^>]*\sd="([^"]+)"', svg)
    assert paths, "no paths"
    body = "\n".join(
        f'        <path android:fillColor="#FF000000" android:pathData="{d}" />' for d in paths
    )
    return f"""<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by scripts/generate_icons.py from Material Symbols (Apache 2.0). Do not edit. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="24dp"
    android:height="24dp"
    android:viewportWidth="{width:g}"
    android:viewportHeight="{height:g}">
    <group android:translateX="{-min_x:g}" android:translateY="{-min_y:g}">
{body}
    </group>
</vector>
"""


def main() -> int:
    source = Path(sys.argv[1])
    entries = []
    for line in TABLE.read_text().splitlines():
        if not line.strip() or line.startswith("#"):
            continue
        cols = line.split("\t") + ["", "", ""]
        sf, material, fill, extra = cols[0], cols[1], cols[2], cols[3]
        weight = "400"
        if extra.startswith("weight="):
            weight = extra.split("=", 1)[1]
        entries.append((sf, material, fill == "fill", weight))

    RES.mkdir(parents=True, exist_ok=True)
    for old in RES.glob("sf_*.xml"):
        if "custom" not in old.read_text()[:300]:
            old.unlink()

    missing = []
    for sf, material, fill, weight in entries:
        if material == "@custom":
            if not (RES / f"{resource_name(sf)}.xml").exists():
                missing.append(f"{sf}: hand-drawn drawable missing")
            continue
        svg_path = source / f"svg-{weight}/package/rounded/{material}{'-fill' if fill else ''}.svg"
        if not svg_path.exists():
            missing.append(f"{sf} -> {svg_path.relative_to(source)}")
            continue
        (RES / f"{resource_name(sf)}.xml").write_text(vector(svg_path.read_text()))

    if missing:
        print("Missing:\n  " + "\n  ".join(missing))
        return 1

    lines = "\n".join(f'    "{sf}" to R.drawable.{resource_name(sf)},' for sf, *_ in entries)
    KOTLIN.parent.mkdir(parents=True, exist_ok=True)
    KOTLIN.write_text(f"""// Generated by scripts/generate_icons.py from design/sf-symbols.tsv. Do not edit.
package com.chrisallenclark.keepr.ui.icons

import com.chrisallenclark.keepr.R

/** SF Symbol name (as stored and used on iOS) to its Android drawable. */
internal val sfSymbolTable: Map<String, Int> = mapOf(
{lines}
)
""")
    print(f"Wrote {len(entries)} symbols")
    return 0


if __name__ == "__main__":
    sys.exit(main())
